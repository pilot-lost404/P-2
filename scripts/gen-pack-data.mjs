/**
 * Generates src/lib/neet/pack-data.generated.ts from content/pack.
 *
 * Why explicit `?raw` imports instead of fs.readFileSync or import.meta.glob:
 *   - `node:fs` and `node:sqlite` do not exist on Cloudflare Workers, which is the
 *     default Nitro target for this app. Reading the pack with fs made the whole
 *     content layer silently fail in production.
 *   - Explicit imports are resolved at build time by any bundler, so the pack ships
 *     as plain strings and works on every runtime (Workers, Node, Deno, tests).
 *   - Generate (don't hand-write) so the file always matches the directory.
 *
 * Usage: node scripts/gen-pack-data.mjs
 */
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const packDir = path.join(root, "content", "pack");
const outFile = path.join(root, "src", "lib", "neet", "pack-data.generated.ts");
// Counts live in their own tiny module: the landing page needs numbers, and importing
// the 1 MB text table just to call `.length` put the whole pack in the browser bundle.
const countsFile = path.join(root, "src", "lib", "neet", "pack-counts.generated.ts");

const files = fs.readdirSync(packDir).sort();
const md = files.filter((f) => f.endsWith(".md"));
const csv = files.filter((f) => f.endsWith(".csv"));

if (md.length === 0) {
  console.error("No markdown found in content/pack — aborting so we do not ship an empty pack.");
  process.exit(1);
}

const ident = (name) => name.replace(/\.(md|csv|json)$/, "").replace(/[^a-zA-Z0-9]+/g, "_");

const lines = [];
lines.push("// AUTO-GENERATED by scripts/gen-pack-data.mjs — do not edit by hand.");
lines.push("// Regenerate after changing anything under content/pack.");
lines.push("//");
lines.push(
  `// ${md.length} markdown volumes and ${csv.length} CSV registries, imported as raw strings so`,
);
lines.push("// the content layer works on any runtime (no node:fs, no node:sqlite).");
lines.push("");

md.forEach((f, i) => {
  lines.push(`import md${i} from "../../../content/pack/${f}?raw"; // ${ident(f)}`);
});
csv.forEach((f, i) => {
  lines.push(`import csv${i} from "../../../content/pack/${f}?raw"; // ${ident(f)}`);
});

lines.push("");
lines.push("/** filename -> raw markdown body */");
lines.push("export const PACK_MARKDOWN: Record<string, string> = {");
md.forEach((f, i) => lines.push(`  ${JSON.stringify(f)}: md${i},`));
lines.push("};");
lines.push("");
lines.push("/** filename -> raw CSV text */");
lines.push("export const PACK_CSV: Record<string, string> = {");
csv.forEach((f, i) => lines.push(`  ${JSON.stringify(f)}: csv${i},`));
lines.push("};");
lines.push("");
lines.push(`export const PACK_FILE_COUNT = ${files.length};`);
lines.push("");

fs.writeFileSync(outFile, lines.join("\n"), "utf8");

// --- counts-only module -------------------------------------------------------
const parse = (text) => {
  const rows = [];
  let row = [];
  let field = "";
  let quoted = false;
  for (let i = 0; i < text.length; i += 1) {
    const ch = text[i];
    if (quoted) {
      if (ch === '"') {
        if (text[i + 1] === '"') {
          field += '"';
          i += 1;
        } else quoted = false;
      } else field += ch;
      continue;
    }
    if (ch === '"') quoted = true;
    else if (ch === ",") {
      row.push(field);
      field = "";
    } else if (ch === "\n") {
      row.push(field);
      rows.push(row);
      row = [];
      field = "";
    } else if (ch !== "\r") field += ch;
  }
  if (field.length || row.length) {
    row.push(field);
    rows.push(row);
  }
  return rows.filter((r) => r.some((c) => c.trim() !== ""));
};

const csvNames = fs.readdirSync(packDir).filter((f) => f.endsWith(".csv"));
const rowCount = (name) => {
  const rows = parse(fs.readFileSync(path.join(packDir, name), "utf8"));
  return Math.max(0, rows.length - 1); // header
};

const words = md.reduce(
  (n, f) =>
    n + fs.readFileSync(path.join(packDir, f), "utf8").trim().split(/\s+/).filter(Boolean).length,
  0,
);

const counts = [
  "// AUTO-GENERATED by scripts/gen-pack-data.mjs — do not edit by hand.",
  "// Counts only, so UI code can show real numbers without bundling the pack text.",
  "",
  "export const packCounts = {",
  `  files: ${files.length},`,
  `  articles: ${md.length},`,
  `  sources: ${rowCount("sources.csv")},`,
  `  prompts: ${rowCount("practice_prompts.csv")},`,
  `  roles: ${rowCount("role_competency_matrix.csv")},`,
  `  words: ${words},`,
  "} as const;",
  "",
].join("\n");
fs.writeFileSync(countsFile, counts, "utf8");

const bytes = files.reduce((n, f) => n + fs.statSync(path.join(packDir, f)).size, 0);
console.log(
  `Wrote ${path.relative(root, outFile)}: ${md.length} volumes + ${csv.length} registries (${(bytes / 1024).toFixed(0)} kB).`,
);
